#!/usr/bin/env node
/**
 * Fetch, pin and trim the third-party schema corpus — design/11 §1.10, `01` §11.6 #5.
 *
 *   node tools/corpus-fetch.mjs [name…] [--accept-pin] [--offline]
 *
 * `migrate verify` being green on three real, third-party schemas is the correctness gate
 * for the migration engine, and a gate is only worth something if the thing it is run
 * against is reproducible. So:
 *
 *  - every download is **sha256-pinned** in this file. A source that changed under us
 *    fails loudly instead of silently changing what the gate means;
 *  - the licence file is fetched with the schema, never assumed;
 *  - trimming is **scripted, not manual**, so the committed `schema.sql` can be
 *    regenerated byte-for-byte from the pinned upstream at any time;
 *  - the trimming uses the kit's own SQL lexer (`sql/statements.ts`), because a `;`
 *    inside a `$$…$$` body is not a statement boundary and a regex over `INSERT` would
 *    cut a function in half.
 *
 * What is removed, and why each is not schema:
 *
 *  - `INSERT` / `COPY` / `SELECT setval(...)` / `UPDATE` / `DELETE` / `TRUNCATE` — data;
 *  - `COPY … FROM stdin;` and everything up to the terminating `\.` — data, and it is
 *    not even SQL;
 *  - psql meta-commands (`\connect`, `\copy`, `\i`, `\echo`, …) — not SQL at all;
 *  - `CREATE`/`DROP`/`ALTER DATABASE`, `\c` — the harness owns the database;
 *  - `GRANT`/`REVOKE`/`ALTER … OWNER TO`/`CREATE ROLE` — cluster-scoped, Tier O in
 *    `06` §2.2, and they name roles that do not exist on the test cluster.
 *
 * Output: `fixtures/corpus/<name>/{schema.sql,LICENSE,SOURCE.md}`, all committed.
 */

